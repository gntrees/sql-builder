// Generates lt/src/schema.lt from a migrated Postgres database.
//
//   bun lt/gen_schema.ts            # write the file
//   bun lt/gen_schema.ts --check    # fail if the committed file is stale
//
// The database is the source of truth: migrations already encode the schema,
// and information_schema tells us the result without re-parsing DDL.
import { SQL } from "bun";

const target = new URL("./src/schema.lt", import.meta.url);
const url = process.env.POSTGRES_URL ?? "postgres://gntrees:gntrees@localhost:5433/gntrees_test";

// Reserved words that cannot be used as a method name in Lingua Tungga.
const RESERVED = new Set([
    "from", "match", "class", "enum", "fn", "let", "if", "else", "for", "while", "return",
    "true", "false", "none", "test", "pub", "static", "mut", "import", "as", "and", "or",
    "not", "self", "in",
]);

type Column = { name: string; type: string; ordinal: number };

function pascal(name: string): string {
    return name
        .split("_")
        .filter(Boolean)
        .map((part) => part[0]!.toUpperCase() + part.slice(1))
        .join("");
}

function method(name: string): string {
    return RESERVED.has(name) ? `${name}_` : name;
}

function ltType(table: string, column: string, sqlType: string): string {
    switch (sqlType) {
        case "integer":
        case "bigint":
        case "smallint":
            return "Int";
        case "text":
        case "character varying":
        case "character":
            return "Str";
        case "boolean":
            return "Bool";
        case "numeric":
        case "double precision":
        case "real":
            return "Float";
        default:
            throw new Error(
                `${table}.${column}: no Lingua Tungga mapping for Postgres type "${sqlType}"; ` +
                    "add it to ltType() and decide the type deliberately",
            );
    }
}

const db = new SQL(url);

const tables = (await db.unsafe(
    `select table_name
       from information_schema.tables
      where table_schema = 'public' and table_type = 'BASE TABLE'
      order by table_name`,
)) as { table_name: string }[];

const columnsByTable = new Map<string, Column[]>();
for (const { table_name } of tables) {
    const columns = (await db.unsafe(
        `select column_name, data_type, ordinal_position
           from information_schema.columns
          where table_schema = 'public' and table_name = $1
          order by ordinal_position`,
        [table_name],
    )) as { column_name: string; data_type: string; ordinal_position: number }[];
    columnsByTable.set(
        table_name,
        columns.map((row) => ({
            name: row.column_name,
            type: row.data_type,
            ordinal: row.ordinal_position,
        })),
    );
}
await db.close();

let out = `// Generated by lt/gen_schema.ts from Postgres. Do not edit by hand.
// Regenerate: bun lt/gen_schema.ts
import Column from "./schema_base.lt"
import Table from "./schema_base.lt"
`;

for (const { table_name } of tables) {
    const columns = columnsByTable.get(table_name) ?? [];
    const cls = pascal(table_name);
    out += `\npub class ${cls} {\n  pub static fn table() -> Table {\n    Table(name: ${JSON.stringify(table_name)})\n  }\n`;
    for (const column of columns) {
        // Fail here rather than emitting a wrong type silently.
        ltType(table_name, column.name, column.type);
        out += `\n  pub static fn ${method(column.name)}() -> Column {\n    Column(table: ${JSON.stringify(table_name)}, name: ${JSON.stringify(column.name)})\n  }\n`;
    }
    out += `}\n`;
}

const current = await Bun.file(target).text().catch(() => "");

if (process.argv.includes("--check")) {
    if (current !== out) {
        console.error("lt/src/schema.lt is stale; run `bun lt/gen_schema.ts` and commit the result");
        const currentLines = current.split("\n");
        const nextLines = out.split("\n");
        for (let index = 0; index < Math.max(currentLines.length, nextLines.length); index += 1) {
            if (currentLines[index] !== nextLines[index]) {
                console.error(`first difference at line ${index + 1}:`);
                console.error(`  committed: ${currentLines[index] ?? "<missing>"}`);
                console.error(`  generated: ${nextLines[index] ?? "<missing>"}`);
                break;
            }
        }
        process.exit(1);
    }
    console.log("lt/src/schema.lt matches the database");
} else {
    await Bun.write(target, out);
    console.log(`wrote ${target.pathname} (${tables.length} tables)`);
}
